import assert from 'node:assert/strict';
import { calcularTurno, criarTurno, dadosPadrao, lerDados, novoFormulario, numero, resumir } from '../src/lib/gestao.ts';

assert.equal(numero('1.234,56'), 1234.56);
assert.equal(numero('23,11'), 23.11);
assert.equal(numero(''), 0);
const dados = dadosPadrao();
assert.equal(calcularTurno(novoFormulario(), dados.custosFixos).liquido, 0);
const form = { ...novoFormulario(), data: '2026-11-15', faturamento: '461,33', combustivel: '92,20', litros: '23,11', kmTrabalhado: '238,1', kmTotal: '246,3', reservas: [{ id: 'r1', nome: 'Janeiro', valor: '20' }, { id: 'r2', nome: 'PIZZA', valor: '18' }] };
const c = calcularTurno(form, dados.custosFixos);
assert.equal(c.totalReservas, 38);
assert.equal(c.precoLitro.toFixed(2), '3.99');
assert.equal(c.consumo.toFixed(2), '10.30');
assert.equal(c.acidente, 9.36);
assert.equal(calcularTurno({ ...form, litros: '' }, []).precoLitro, 0);
const antigo = criarTurno(form, dados.custosFixos, 'legado');
const bruto = JSON.stringify({ ...dados, historico: [antigo] });
const carregado = lerDados(JSON.parse(bruto));
assert.equal(JSON.stringify(carregado), bruto);
const editado = criarTurno({ ...novoFormulario([], antigo), faturamento: '500' }, [], 'legado', antigo);
assert.equal(editado.custosFixosDia, antigo.custosFixosDia);
assert.deepEqual(editado.detalheCustosFixosDia, antigo.detalheCustosFixosDia);
assert.equal(editado.id, antigo.id);
const retirada = { ...antigo, id: 'retirada', tipo: 'avulso_saida', faturamentoBruto: 0, combustivel: 0, litros: 0, kmTrabalhado: 0, reservaFevereiro: 0, reservaInvestimento: 0, reservaAcidente: 0, detalheCustosFixosDia: {}, reservasDiariasDia: [], saidas: [{ id: 's', nome: 'Uso da reserva', valor: 10, origem: 'diaria:r2' }], totalDespesas: 10, liquido: -10 };
const resumo = resumir([antigo, retirada]);
assert.equal(resumo.liquido, antigo.liquido);
assert.equal(resumo.reservas.r2.valor, 8);
assert.equal(resumir([antigo, { ...antigo, id: 'segundo-turno' }]).dias, 1);
console.log('PASS: combustível, consumo, reservas, arredondamento, compatibilidade do histórico, edição com rateio original e retiradas sem desconto duplicado.');
